let qIndex = 0, score = 0, timer = 600, lang = "en";
let examEnded = false;

function startExam() {
    let name = document.getElementById("studentName").value;
    if (name === "") { alert("Enter name"); return; }
    document.getElementById("startBox").style.display = "none";
    document.getElementById("examBox").style.display = "block";
    startTimer();
    loadQuestion();
}

function loadQuestion() {
    let q = questions[qIndex];
    document.getElementById("question").innerText = q[lang];
    let optBox = document.getElementById("options");
    optBox.innerHTML = "";

    // यहाँ सुधार किया गया है: lang के आधार पर सही ऑप्शन्स चुनना
    let currentOptions = q.options[lang]; 

    currentOptions.forEach((o, i) => {
        optBox.innerHTML += `
        <div class="option" style="margin: 10px 0;">
            <input type="radio" name="opt" value="${i}" id="opt${i}"> 
            <label for="opt${i}">${o}</label>
        </div>`;
    });
}

function nextQuestion() {
    let sel = document.querySelector('input[name="opt"]:checked');
    
    // अगर उत्तर सही है तो स्कोर बढ़ाएं
    if (sel && parseInt(sel.value) === questions[qIndex].answer) {
        score++;
    }

    // अगले प्रश्न पर जाएँ या टेस्ट खत्म करें
    if (qIndex < questions.length - 1) {
        qIndex++;
        loadQuestion();
    } else {
        submitTest();
    }
}

function submitTest(auto = false) {
    if (examEnded) return;
    examEnded = true;
    document.getElementById("examBox").style.display = "none";
    let name = document.getElementById("studentName").value;

    let results = JSON.parse(localStorage.getItem("results")) || [];
    results.push({ name: name, score: score });
    localStorage.setItem("results", JSON.stringify(results));

    document.getElementById("resultBox").style.display = "block";
    document.getElementById("resultBox").innerHTML = `
    <div style="text-align:center; padding: 20px;">
        <h2>✅ Your Test is Over</h2>
        <p><b>Name:</b> ${name}</p>
        <p><b>Total Score:</b> ${score} / ${questions.length}</p>
    </div>`;
}

function startTimer() {
    let t = setInterval(() => {
        if (examEnded) { clearInterval(t); return; }
        timer--;
        let m = Math.floor(timer / 60);
        let s = timer % 60;
        document.getElementById("timer").innerText = `${m}:${s < 10 ? '0' + s : s}`;
        if (timer <= 0) { clearInterval(t); submitTest(true); }
    }, 1000);
}

function toggleLanguage() {
    lang = (lang === "en") ? "hi" : "en";
    loadQuestion();
}

// टैब बदलने पर ऑटो सबमिट (चीटिंग रोकने के लिए)
document.addEventListener("visibilitychange", () => {
    if (document.hidden && !examEnded) submitTest(true);
});